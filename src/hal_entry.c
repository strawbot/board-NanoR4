/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    /* Arduino Nano R4 quirk: the DFU bootloader jumps to user code via direct
     * register manipulation (not NVIC_SystemReset), leaving PRIMASK=1 and VTOR
     * still at 0x0 (bootloader vectors). Fix both before anything else runs:
     *   - VTOR: user vectors live at 0x4000 (bootloader owns 0x0–0x3FFF)
     *   - PRIMASK: clear so FSP init, USB, and the scheduler work correctly */
    SCB->VTOR = 0x00004000UL;
    __enable_irq();

    /* Visible "firmware alive" marker — three short LED pulses before we
     * touch the scheduler or transport. If you don't see this after reset,
     * the firmware isn't reaching hal_entry at all (check VTOR / memory
     * regions / upload). */

    /* Enable the DWT cycle counter for hi-res timing (sysTicks()).
     * Required by project_defs.h: #define sysTicks() (Long)(DWT->CYCCNT) */
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL   |= DWT_CTRL_CYCCNTENA_Msk;

    /* Wake up 2nd core if this is first core and we are inside a multicore project. */
#if (0 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && !BSP_TZ_NONSECURE_BUILD

#if BSP_TZ_SECURE_BUILD
    /* Take semaphore so 2nd core can clear it */
    R_BSP_IpcSemaphoreTake(&g_core_start_semaphore);
#endif

    R_BSP_SecondaryCoreStart();

#if BSP_TZ_SECURE_BUILD
    /* Wait for 2nd core to start and clear semaphore */
    while(FSP_ERR_IN_USE == R_BSP_IpcSemaphoreTake(&g_core_start_semaphore))
    {
        ;
    }
#endif
#endif

#if (1 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && BSP_TZ_SECURE_BUILD
    /* Signal to 1st core that 2nd core has started */
    R_BSP_IpcSemaphoreGive(&g_core_start_semaphore);
#endif


#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif

    stack_canary_init();   /* fill stack with 0xDEADBEEF before any deep calls */

    /* TimbreOS bring-up. init_tea() calls init_clocks() internally
     * (see TimbreOS/tea.c:init_tea) so we do NOT call init_clocks() again.
     * The build banner is printed *after* usart_transport_init() because
     * init_clocks runs before the transport is up, and output() will spin
     * forever if emitq has no drain path.
     *
     * usart_drain() after each print keeps emitq shallow. output() blocks when
     * the queue fills and runs actions while it waits, but running actions does
     * not signal EmitEvent — so if the TX chain has gone idle nothing restarts
     * it and the wait never ends. usart_drain() calls usart_emit() directly,
     * which re-arms it. See Docs/output-backpressure-design.md; the proper fix
     * is for output() to kick the transport itself, after which this goes away. */
    dac_init();
    adc_init();
    muscle_wire_init();   // open GPT3 PWM on P003 before scheduler starts
    i2c1_init();          // IIC1: SCL=P100, SDA=P101, 400 kHz — limb array bus
    init_tea();
    usart_transport_init();

    print_build_banner();
    usart_drain();

    init_cli();
    usart_drain();         // init_cli() prints its own banner

    fs_hw_flash_init();    // mount (formatting once if blank/unreadable) before
                            // anything might want to read/write a file
    usart_drain();

    // 4-limb build: the middle shift register (limbs 3, 4) stays zero.
    // No muscle_bind_hw() yet — the PWM drive board is still to be
    // prototyped, so the scheduler runs as a simulation (see `muscles`).
    // Likewise no posture_bind_hw() until the new board's ICM-42688-P is
    // up; until then the gait runs without IMU feedback.
    muscle_init(MUSCLE_LIMBS_4);
    posture_init();
    gait_init();

    // limb_io_init() calls in() to arm its first sweep tick, so it must
    // come after init_tea() (unlike the peripheral opens above, which
    // don't touch the scheduler).

    // disabled for running cli tests; look at cli enabler.
    // limb_io_init();

    /* USB comes up LAST, immediately before the run loop, so the first USB
     * interrupt is serviced on the next scheduler pass rather than after a few
     * hundred milliseconds of console traffic. Do not move this earlier: nothing
     * can service USBFS_INT until run() is turning.
     *
     * The TinyUSB device stack itself is currently disabled — usb_transport_init()
     * performs the USBFS hardware reset and returns. That reset is required: the
     * bootloader hands over without detaching from the bus, so after a DFU
     * download USBFS is still live and the host still attached.
     * See Docs/usb-handoff.md.
     *
     * env:nano_r4_usbtest swaps this for usb_native_test_init(), which
     * opens RASC's native r_usb_basic + r_usb_pcdc stack instead — a smoke
     * test for whether the native driver's interrupt path is more reliable
     * than TinyUSB's. See Docs/usb-handoff.md, "Native stack smoke test". */
#ifdef USE_NATIVE_USB_STACK
    usb_native_test_init();
#else
    usb_transport_init();
#endif

    while (1) {
        run();
        micro_sleep();   // __WFI — wake on any interrupt (timer, UART RX/TX)
    }
}

